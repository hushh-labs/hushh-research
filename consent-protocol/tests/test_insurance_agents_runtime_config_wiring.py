"""The insurance agent directory's base URL and key must survive a deploy.

The sibling of test_advisors_runtime_config_wiring, and for the same reason:
BACKEND_RUNTIME_CONFIG_JSON is regenerated by
scripts/ops/sync_backend_runtime_secrets.py on every deploy, so a value only
written into Secret Manager by hand is overwritten on the next release and the
surface silently reports "not configured".

The key half matters even more here than for advisers. Read access to the home
project is a per-secret grant that does not come with any lane's own
project-level roles, so a lane that was never granted it mirrors nothing and
stays inert — which is correct, but only if the mirror is actually wired.
"""

from __future__ import annotations


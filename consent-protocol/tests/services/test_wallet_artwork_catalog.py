import hashlib

import pytest

from hushh_mcp.services.wallet_artwork_catalog import (
    ArtworkAsset,
    ArtworkCatalog,
    ProviderMatch,
    approved_assets,
    read_asset,
    resolve_artwork,
)


def asset(**changes):
    return ArtworkAsset.model_validate(
        {
            "asset_id": "synthetic-blue",
            "issuer_id": "synthetic-issuer",
            "product_id": "synthetic-product",
            "family": "synthetic",
            "variant_id": "blue",
            "label": "Synthetic blue",
            "country": "US",
            "network": "visa",
            "iin_prefixes": ["424242"],
            "digest": "a" * 64,
            "mime": "image/png",
            "rights_reference": "test-owned-fixture",
            "provenance": "generated by test",
            "approved_by": "test",
            "approved_at": "2000-01-01T00:00:00Z",
            "rights_policy": "perpetual_private_display",
            "status": "approved",
            "sanitized": True,
            **changes,
        }
    )


def catalog(*assets):
    return ArtworkCatalog(version="test-1", assets=list(assets))


def test_default_has_no_fabricated_issuer_or_exact_artwork(monkeypatch):
    monkeypatch.delenv("HUSHH_WALLET_ARTWORK_CATALOG_PATH", raising=False)
    result = resolve_artwork("424242", 16, "visa")
    assert result["match"] == "unknown" and result["provider"] == "unconfigured"
    assert result["variants"] == []


def test_same_iin_is_not_exact_product_proof():
    result = resolve_artwork("42424200", 16, "visa", catalog=catalog(asset()))
    assert result["match"] == "issuer_only" and len(result["variants"]) == 1
    assert result["metadata"]["country"] == "US"
    assert result["metadata"]["productFamily"] is None
    result = resolve_artwork(
        "424242",
        16,
        "visa",
        catalog=catalog(asset(), asset(asset_id="synthetic-red", variant_id="red")),
    )
    assert result["match"] == "ambiguous" and len(result["variants"]) == 2


def test_exact_requires_authorized_product_and_variant_proof():
    class Provider:
        def identify(self, **payload):
            assert payload == {"iin_prefix": "42424200", "pan_length": 16, "network": "visa"}
            return ProviderMatch(
                issuer_id="synthetic-issuer",
                product_id="synthetic-product",
                variant_id="blue",
                product_verified=True,
            )

    result = resolve_artwork("42424200", 16, "visa", provider=Provider(), catalog=catalog(asset()))
    assert result["match"] == "exact" and result["provider"] == "configured"


def test_outage_and_revoked_or_unapproved_artwork_fall_back():
    class Offline:
        def identify(self, **payload):
            raise RuntimeError("never echo provider detail")

    assert (
        resolve_artwork("424242", 16, "visa", provider=Offline(), catalog=catalog())["provider"]
        == "unavailable"
    )
    assert (
        approved_assets(
            catalog(asset(status="revoked"), asset(status="pending"), asset(sanitized=False))
        )
        == []
    )


@pytest.mark.parametrize("prefix", ["4242424242424242", "42424", "4242420", "٤٢٤٢٤٢", "abc123"])
def test_service_rejects_any_non_permitted_iin(prefix):
    with pytest.raises(ValueError):
        resolve_artwork(prefix, 16, "visa")


def test_license_approval_and_provenance_are_required():
    for field in ["rights_reference", "provenance", "approved_by", "approved_at"]:
        with pytest.raises(ValueError):
            asset(**{field: ""})


@pytest.mark.parametrize(
    "changes",
    [
        {"rights_policy": "time_limited"},
        {"approved_by": "   "},
        {"provenance": "\n"},
        {"approved_at": "2099-01-01T00:00:00Z"},
        {"approved_at": "2000-01-01T00:00:00"},
    ],
)
def test_unsupported_rights_and_unverifiable_approvals_fail_closed(changes):
    with pytest.raises(ValueError):
        asset(**changes)


def test_asset_is_local_bounded_digest_bound_and_revocation_is_immediate(tmp_path, monkeypatch):
    data = bytes.fromhex("89504e470d0a1a0a") + b"synthetic owned raster"
    digest = hashlib.sha256(data).hexdigest()
    (tmp_path / "assets").mkdir()
    file = tmp_path / "assets" / (digest + ".png")
    file.write_bytes(data)
    path = tmp_path / "catalog.json"
    path.write_text(catalog(asset(digest=digest)).model_dump_json())
    monkeypatch.setenv("HUSHH_WALLET_ARTWORK_CATALOG_PATH", str(path))
    assert read_asset(digest) == (data, "image/png")
    file.write_bytes(b"altered")
    with pytest.raises(ValueError):
        read_asset(digest)
    path.write_text(catalog(asset(digest=digest, status="revoked")).model_dump_json())
    with pytest.raises(FileNotFoundError):
        read_asset(digest)

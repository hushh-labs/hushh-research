@pytest.mark.asyncio
async def test_relay_accepts_pcm_sequence_metadata_nested_in_realtime_input(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Exercise the exact browser wire shape, not only the gate in isolation."""

    command_relay = _location_command_relay_or_skip()

    class _Socket:
        def __init__(self) -> None:
            pcm = b64encode(b"\x00\x01\x02\x03").decode("ascii")
            self._frames = [
                json.dumps({"type": "app_context", "contextId": "ctx", "appContext": {}}),
                json.dumps(
                    {
                        "type": "location_command_begin",
                        "protocolVersion": LOCATION_COMMAND_PROTOCOL_VERSION,
                        "turnId": "turn_123",
                        "startSequence": 1,
                    }
                ),
                json.dumps(
                    {
                        "realtimeInput": {
                            "audio": {
                                "data": pcm,
                                "mimeType": "audio/pcm;rate=16000",
                            },
                            "locationCommand": {"turnId": "turn_123", "sequence": 1},
                        }
                    }
                ),
            ]
            self.sent: list[str] = []

        async def receive_text(self) -> str:
            if self._frames:
                return self._frames.pop(0)
            await asyncio.Event().wait()
            raise AssertionError("unreachable")

        async def send_text(self, value: str) -> None:
            self.sent.append(value)

    class _Session:
        setup_complete = object()

        def __init__(self) -> None:
            self.sent: list[dict[str, object]] = []
            self.audio_received = asyncio.Event()

        async def send_realtime_input(self, **kwargs: object) -> None:
            self.sent.append(kwargs)
            if "audio" in kwargs:
                self.audio_received.set()

        async def receive(self):
            await self.audio_received.wait()
            yield SimpleNamespace(
                server_content=SimpleNamespace(
                    input_transcription=SimpleNamespace(text="do location onboarding"),
                    interrupted=False,
                    turn_complete=False,
                )
            )
            yield SimpleNamespace(
                server_content=SimpleNamespace(
                    input_transcription=None,
                    interrupted=False,
                    turn_complete=True,
                )
            )

    class _Live:
        def __init__(self, session: _Session) -> None:
            self._session = session

        @asynccontextmanager
        async def connect(self, **_kwargs: object):
            yield self._session

    class _Runtime:
        async def plan(self, **kwargs: object) -> LocationCommandPlanV1:
            assert kwargs["transcript"] == "do location onboarding"
            return LocationCommandPlanV1(
                turn_id="turn_123",
                immediate_result=LocationCommandResultV1(
                    turn_id="turn_123",
                    outcome="ask",
                    reason_code="selection_required",
                ),
            )

        async def advance(
            self, plan: LocationCommandPlanV1, **_kwargs: object
        ) -> LocationCommandResultV1:
            assert plan.immediate_result is not None
            return plan.immediate_result

    socket = _Socket()
    session = _Session()
    client = SimpleNamespace(aio=SimpleNamespace(live=_Live(session)))

    monkeypatch.setattr(command_relay, "get_location_command_runtime", lambda: _Runtime())

    await command_relay._run_location_command_relay(
        socket,  # type: ignore[arg-type]
        uid="owner",
        client=client,
        model=DEFAULT_LOCATION_COMMAND_TRANSCRIBE_MODEL,
    )

    assert any("audio" in frame for frame in session.sent)
    assert not any("activity_start" in frame for frame in session.sent)
    assert not any("activity_end" in frame for frame in session.sent)
    wire = "\n".join(socket.sent)
    payloads = [json.loads(frame) for frame in socket.sent]
    assert {"serverContent": {"turnComplete": True}} in payloads
    assert any(
        payload.get("locationCommandResult", {}).get("outcome") == "ask" for payload in payloads
    )
    # A provider turn is untagged. After a terminal command result and the
    # post-completion drain, the relay must rotate instead of accepting a
    # second physical hold on this Live session.
    assert any(
        payload.get("sessionEnded", {}).get("reason") == "location_command_boundary_rollover"
        for payload in payloads
    )
    assert "turn_mismatch" not in wire
    assert "do location onboarding" not in wire



class _StandaloneCommandRelayHarness:
    """Test seam that invokes the standalone command relay, never the chat route.

    The runtime tests were originally imported with a compatibility seam for
    the conversational relay.  Keep their realistic socket/provider fakes,
    but construct the standalone relay's explicit dependency bundle here so
    the tests exercise the command-only transport and cannot accidentally
    re-enable the chat route.
    """

    def __init__(self, module: ModuleType) -> None:
        self._module = module
        self.WebSocketDisconnect = module.WebSocketDisconnect
        self.get_location_command_runtime = location_command_module.get_location_command_runtime
        self._LOCATION_COMMAND_RESOLUTION_TIMEOUT_SECONDS = module._PLANNING_TIMEOUT_SECONDS

    def _build_location_command_live_config(self, genai_types: object) -> object:
        return self._module._location_command_live_config(genai_types)

    def _location_command_provider_setup_observed(self, session: object) -> bool:
        return self._module._provider_setup_observed(session)

    async def _run_location_command_relay(
        self,
        websocket: object,
        *,
        uid: str,
        client: object,
        model: str,
    ) -> None:
        dependencies = self._module._CommandRuntimeDependencies(
            runtime_factory=self.get_location_command_runtime,
            turn_gate_factory=LocationCommandTurnGate,
            runtime_enabled=lambda: True,
            transcribe_model=lambda: model,
            protocol_version=self._module.LOCATION_COMMAND_PROTOCOL_VERSION,
        )
        previous_timeout = self._module._PLANNING_TIMEOUT_SECONDS
        self._module._PLANNING_TIMEOUT_SECONDS = self._LOCATION_COMMAND_RESOLUTION_TIMEOUT_SECONDS
        try:
            await self._module._run_location_command_relay(
                websocket,  # type: ignore[arg-type]
                uid=uid,
                client=client,
                model=model,
                dependencies=dependencies,
            )
        finally:
            self._module._PLANNING_TIMEOUT_SECONDS = previous_timeout


def _location_command_relay_or_skip() -> _StandaloneCommandRelayHarness:
    """Return the standalone command-only relay under test."""

    try:
        from api.routes.one import location_command_relay
    except Exception as exc:  # noqa: BLE001 - production fails closed
        if exc.__class__.__name__ == "CapabilityGraphArtifactError":
            pytest.skip("Capability graph artifact is being regenerated by the graph lane.")
        raise
    return _StandaloneCommandRelayHarness(location_command_relay)



@pytest.mark.asyncio
async def test_durable_advance_is_not_reported_as_a_semantic_routing_timeout(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Once a selected plan enters a durable adapter, it owns settlement."""

    command_relay = _location_command_relay_or_skip()
    monkeypatch.setattr(command_relay, "_LOCATION_COMMAND_RESOLUTION_TIMEOUT_SECONDS", 0.01)

    class _Socket:
        _DISCONNECT = object()

        def __init__(self) -> None:
            self.frames: asyncio.Queue[object] = asyncio.Queue()
            self.sent: list[str] = []
            self.working_sent = asyncio.Event()
            self.result_sent = asyncio.Event()

        async def receive_text(self) -> str:
            frame = await self.frames.get()
            if frame is self._DISCONNECT:
                raise command_relay.WebSocketDisconnect()
            return str(frame)

        async def send_text(self, value: str) -> None:
            self.sent.append(value)
            payload = json.loads(value)
            state = payload.get("locationCommandState")
            if isinstance(state, dict) and state.get("state") == "working":
                self.working_sent.set()
            result = payload.get("locationCommandResult")
            if isinstance(result, dict) and result.get("settlement") == "verified":
                self.result_sent.set()

        async def feed(self, frame: dict[str, object] | object) -> None:
            await self.frames.put(frame if frame is self._DISCONNECT else json.dumps(frame))

    class _Session:
        setup_complete = object()

        def __init__(self) -> None:
            self.audio_received = asyncio.Event()

        async def send_realtime_input(self, **kwargs: object) -> None:
            if "audio" in kwargs:
                self.audio_received.set()

        async def receive(self):
            await self.audio_received.wait()
            yield SimpleNamespace(
                server_content=SimpleNamespace(
                    input_transcription=SimpleNamespace(text="create my location circle"),
                    interrupted=False,
                    turn_complete=False,
                )
            )
            yield SimpleNamespace(
                server_content=SimpleNamespace(
                    input_transcription=None,
                    interrupted=False,
                    turn_complete=True,
                )
            )
            while True:
                await asyncio.Event().wait()

    class _Live:
        def __init__(self, session: _Session) -> None:
            self._session = session

        @asynccontextmanager
        async def connect(self, **_kwargs: object):
            yield self._session

    class _Runtime:
        def __init__(self) -> None:
            self.advance_started = asyncio.Event()
            self.allow_settlement = asyncio.Event()

        async def plan(self, **kwargs: object) -> LocationCommandPlanV1:
            return LocationCommandPlanV1(
                turn_id=str(kwargs["turn_id"]),
                selected_capability_id="location.create_circle",
                disposition="EXECUTE_SERVER_VERIFIED",
                slots={"name": "My Circle"},
            )

        async def advance(
            self, plan: LocationCommandPlanV1, **_kwargs: object
        ) -> LocationCommandResultV1:
            assert plan.requires_durable_advance is True
            self.advance_started.set()
            await self.allow_settlement.wait()
            return LocationCommandResultV1(
                turn_id=plan.turn_id,
                outcome="execute_started",
                action_id="location.create_circle",
                settlement="verified",
            )

    socket = _Socket()
    session = _Session()
    runtime = _Runtime()
    client = SimpleNamespace(aio=SimpleNamespace(live=_Live(session)))
    pcm = b64encode(b"\x00\x01\x02\x03").decode("ascii")

    monkeypatch.setattr(command_relay, "get_location_command_runtime", lambda: runtime)

    await socket.feed({"type": "app_context", "contextId": "ctx", "appContext": {}})
    await socket.feed(
        {
            "type": "location_command_begin",
            "protocolVersion": LOCATION_COMMAND_PROTOCOL_VERSION,
            "turnId": "turn_durable",
            "startSequence": 1,
        }
    )
    await socket.feed(
        {
            "realtimeInput": {
                "audio": {"data": pcm, "mimeType": "audio/pcm;rate=16000"},
                "locationCommand": {"turnId": "turn_durable", "sequence": 1},
            }
        }
    )
    relay = asyncio.create_task(
        command_relay._run_location_command_relay(
            socket,  # type: ignore[arg-type]
            uid="owner",
            client=client,
            model=DEFAULT_LOCATION_COMMAND_TRANSCRIBE_MODEL,
        )
    )
    try:
        await asyncio.wait_for(runtime.advance_started.wait(), timeout=1)
        await asyncio.wait_for(socket.working_sent.wait(), timeout=1)
        # Deliberately exceed the semantic selection deadline: the durable
        # adapter is allowed to settle through its own idempotent lifecycle.
        await asyncio.sleep(0.03)
        assert not any(
            json.loads(frame).get("locationCommandResult", {}).get("reasonCode")
            == "resolution_timeout"
            for frame in socket.sent
        )
        runtime.allow_settlement.set()
        await asyncio.wait_for(socket.result_sent.wait(), timeout=1)
        results = [
            json.loads(frame).get("locationCommandResult")
            for frame in socket.sent
            if isinstance(json.loads(frame).get("locationCommandResult"), dict)
        ]
        assert any(
            item.get("actionId") == "location.create_circle"
            and item.get("settlement") == "verified"
            for item in results
        )
    finally:
        await socket.feed(_Socket._DISCONNECT)
        await asyncio.wait_for(relay, timeout=1)



def test_cancelled_turn_cannot_be_replaced_until_post_completion_boundary_drains() -> None:
    """Late untagged provider content from A must never route as command B."""

    gate = LocationCommandTurnGate()
    first, error = gate.begin(_begin("turn_a"), provider_ready=True, context_ready=True)
    assert error is None and first is not None
    assert gate.accept_audio({"turnId": "turn_a", "sequence": 1}) is None
    assert gate.end(_end("turn_a", cancelled=True))[1] is None
    # Cancellation forces a provider-session rollover. An old untagged
    # provider fragment can never be attached to B on this session.
    gate.fail()
    gate.mark_result_settled(turn_id="turn_a")

    second, error = gate.begin(_begin("turn_b"), provider_ready=True, context_ready=True)
    assert second is None
    assert error == "provider_turn_draining"

    # This old A fragment is ignored while A remains the gate owner.
    gate.receive_final_transcript("create a circle called old command")
    assert gate.take_resolution() is None


def test_cancelled_turn_cannot_be_replaced_until_untagged_provider_events_drain() -> None:
    gate = LocationCommandTurnGate()
    turn, error = gate.begin(_begin("turn_old"), provider_ready=True, context_ready=True)

    assert error is None and turn is not None
    assert gate.accept_audio({"turnId": "turn_old", "sequence": 1}) is None
    assert gate.end(_end("turn_old", cancelled=True))[1] is None
    # A final old-turn event may still arrive after cancel. It is discarded and
    # cannot become input for the next command because the relay reconnects.
    gate.receive_final_transcript("old command must never route")
    next_turn, next_error = gate.begin(_begin("turn_new"), provider_ready=True, context_ready=True)
    assert next_turn is None
    assert next_error == "provider_turn_draining"
    gate.mark_result_settled(turn_id="turn_old")
    next_turn, next_error = gate.begin(_begin("turn_new"), provider_ready=True, context_ready=True)
    assert next_turn is None
    assert next_error == "provider_turn_draining"
    assert gate.take_resolution() is None



#!/usr/bin/env python3
"""Fail-closed Cloud Run to Cloud SQL connection admission check.

This command is read only. The default pre-deploy phase reserves one new
revision of each configured database-using service during deployment overlap.
Scoped releases may name only the services that will create a new revision.
Use --phase post-release to check retained capacity without another hypothetical
candidate. Both phases include retained revisions, jobs and administrative reserve.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Literal

DEFAULT_PROFILE = Path(__file__).resolve().parents[2] / "config/runtime-capacity.json"
CAPACITY_PHASES = ("pre-deploy", "post-release")
CapacityPhase = Literal["pre-deploy", "post-release"]
POOL_KEYS = (
    "DB_POOL_MAX_SIZE",
    "DB_SQLALCHEMY_POOL_SIZE",
    "DB_SQLALCHEMY_MAX_OVERFLOW",
)
FRONTEND_SERVICE = "hushh-webapp"
FRONTEND_DB_ENV = re.compile(
    r"^(?:DB|DATABASE|POSTGRES|PG|CLOUD_SQL|CLOUDSQL|SQLALCHEMY|JDBC)"
)
FRONTEND_DB_VALUE = re.compile(
    r"(?:postgres(?:ql)?://|/cloudsql/|hushh-uat-pg|cloudsql-instances)", re.I
)
FRONTEND_ALLOWED_PROJECT_ROLES = frozenset(
    {
        "roles/secretmanager.secretAccessor",
        "roles/logging.logWriter",
        "roles/monitoring.metricWriter",
        "roles/cloudtrace.agent",
    }
)


class BudgetError(ValueError):
    """Inventory or policy is incomplete, so admission cannot be proved."""


def positive_int(value: Any, label: str, *, zero_ok: bool = False) -> int:
    if isinstance(value, bool) or not str(value).isdigit():
        raise BudgetError(f"{label}: expected a non-negative integer, got {value!r}")
    number = int(value)
    if not zero_ok and number == 0:
        raise BudgetError(f"{label}: expected a positive integer")
    return number


def gcloud_json(*args: str) -> Any:
    command = ["gcloud", *args, "--format=json"]
    try:
        result = subprocess.run(command, check=True, capture_output=True, text=True)
        return json.loads(result.stdout)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        detail = (
            exc.stderr.strip()
            if isinstance(exc, subprocess.CalledProcessError)
            else str(exc)
        )
        raise BudgetError(
            f"Cloud inventory unavailable ({' '.join(command[:4])}): {detail}"
        ) from exc


def named_container(spec: dict[str, Any], name: str, label: str) -> dict[str, Any]:
    containers = spec.get("containers")
    if not isinstance(containers, list):
        raise BudgetError(f"{label}: container list unavailable")
    matches = [item for item in containers if item.get("name") == name]
    if len(matches) == 1:
        return matches[0]
    # Older Cloud Run revisions were deployed with an autogenerated container
    # name (for example consent-protocol-1). A single container is unambiguous.
    if not matches and len(containers) == 1:
        return containers[0]
    raise BudgetError(f"{label}: expected exactly one application container")


def env_values(container: dict[str, Any], label: str) -> dict[str, str]:
    env = container.get("env")
    if not isinstance(env, list):
        raise BudgetError(f"{label}: environment unavailable")
    result: dict[str, str] = {}
    for item in env:
        name = item.get("name")
        if name in result:
            raise BudgetError(f"{label}: duplicate {name}")
        if isinstance(name, str) and "value" in item:
            result[name] = str(item["value"])
    return result


def revision_workers(
    container: dict[str, Any], settings: dict[str, Any], name: str
) -> int:
    """Count the actual launcher workers; conflicting declarations fail closed."""
    command = container.get("command") or []
    if command and Path(command[0]).name in {"sh", "bash", "dash", "zsh"}:
        raise BudgetError(f"{name}: uninspectable explicit shell launcher")
    declarations: list[int] = []
    for item in container.get("env", []):
        if item.get("name") == "WEB_CONCURRENCY":
            if "value" not in item:
                raise BudgetError(f"{name}: WEB_CONCURRENCY must be inspectable")
            declarations.append(positive_int(item["value"], f"{name} WEB_CONCURRENCY"))
    args = [*(container.get("command") or []), *(container.get("args") or [])]
    for index, argument in enumerate(args):
        if argument in {"-w", "--workers"}:
            if index + 1 >= len(args):
                raise BudgetError(f"{name}: malformed worker count")
            declarations.append(positive_int(args[index + 1], f"{name} workers"))
        elif isinstance(argument, str) and argument.startswith("--workers="):
            declarations.append(
                positive_int(argument.split("=", 1)[1], f"{name} workers")
            )
        elif (
            isinstance(argument, str)
            and argument.startswith("-w")
            and len(argument) > 2
        ):
            declarations.append(positive_int(argument[2:], f"{name} workers"))
        elif isinstance(argument, str) and (
            re.search(r"(?:^|[\s\'\"])(?:--workers(?:=|\b)|-w)", argument)
        ):
            raise BudgetError(f"{name}: uninspectable shell worker override")
    if len(set(declarations)) > 1:
        raise BudgetError(f"{name}: conflicting worker declarations")
    return (
        declarations[0]
        if declarations
        else positive_int(
            settings["workers_per_instance"], f"{name} reviewed image default workers"
        )
    )


def pool_capacity(
    container: dict[str, Any], label: str, *, required: bool = True
) -> int:
    """Count the runtime's effective finite pools, including optional modifiers."""
    env = env_values(container, label)
    controls = {*POOL_KEYS, "DB_POOL_MIN_SIZE", "DB_SQLALCHEMY_USE_NULL_POOL"}
    for item in container.get("env", []):
        if item.get("name") in controls and item["name"] not in env:
            raise BudgetError(f"{label}: uninspectable {item['name']}")
    if env.get("DB_SQLALCHEMY_USE_NULL_POOL", "").strip().lower() in {
        "1",
        "true",
        "yes",
        "on",
    }:
        raise BudgetError(f"{label}: NullPool has no reviewed finite connection bound")
    present = [key in env for key in POOL_KEYS]
    if not required and not any(present) and "DB_POOL_MIN_SIZE" not in env:
        return 0
    if not all(present):
        raise BudgetError(f"{label}: partial DB pool settings: missing {', '.join(key for key in POOL_KEYS if key not in env)}")
    asynchronous, synchronous, overflow = [
        positive_int(
            env[key], f"{label} {key}", zero_ok=key == "DB_SQLALCHEMY_MAX_OVERFLOW"
        )
        for key in POOL_KEYS
    ]
    # Match db.connection.get_pool: an omitted minimum defaults to two and
    # a larger minimum raises the effective asyncpg maximum.
    minimum = positive_int(
        env.get("DB_POOL_MIN_SIZE", "2"), f"{label} DB_POOL_MIN_SIZE", zero_ok=True
    )
    return max(asynchronous, minimum) + synchronous + overflow


def revision_connections(
    revision: dict[str, Any],
    service: str,
    settings: dict[str, Any],
    database_connection_name: str,
) -> dict[str, Any]:
    metadata = revision.get("metadata") or {}
    name = metadata.get("name")
    if not isinstance(name, str) or not name.startswith(f"{service}-"):
        raise BudgetError(f"{service}: revision name missing or mismatched")
    annotations = metadata.get("annotations") or {}
    cloudsql = annotations.get("run.googleapis.com/cloudsql-instances", "")
    if database_connection_name not in cloudsql.split(","):
        raise BudgetError(
            f"{name}: expected Cloud SQL attachment {database_connection_name}"
        )
    maximum = positive_int(
        annotations.get("autoscaling.knative.dev/maxScale"),
        f"{name} revision max instances",
    )
    spec = revision.get("spec") or {}
    container = named_container(spec, settings["container"], name)
    connections_per_worker = pool_capacity(container, name)
    workers = revision_workers(container, settings, name)
    return {
        "name": name,
        "max_instances": maximum,
        "workers_per_instance": workers,
        "connections_per_worker": connections_per_worker,
        "connections": maximum * workers * connections_per_worker,
    }


def candidate_connections(service: str, settings: dict[str, Any]) -> dict[str, Any]:
    candidate = settings["candidate"]
    maximum = positive_int(
        candidate["max_instances"], f"{service} candidate max instances"
    )
    workers = positive_int(
        candidate["workers_per_instance"], f"{service} candidate workers"
    )
    pools = [
        positive_int(
            candidate[key],
            f"{service} candidate {key}",
            zero_ok=(key == "sqlalchemy_max_overflow"),
        )
        for key in (
            "asyncpg_pool_max",
            "sqlalchemy_pool_size",
            "sqlalchemy_max_overflow",
        )
    ]
    return {
        "name": f"{service}:new-candidate",
        "max_instances": maximum,
        "workers_per_instance": workers,
        "connections_per_worker": sum(pools),
        "connections": maximum * workers * sum(pools),
    }


def inherited_candidate_connections(
    service: str,
    settings: dict[str, Any],
    service_doc: dict[str, Any],
    revisions: list[dict[str, Any]],
    database_connection_name: str,
) -> dict[str, Any]:
    """Reserve the largest of policy, the service template, and serving revision.

    A service update that changes only image and selected env vars inherits the
    live template's scale and DB pools. The serving revision is a second bound
    for scale, pool, or explicit worker-argument drift from that template.
    """
    template = (service_doc.get("spec") or {}).get("template")
    if not isinstance(template, dict):
        raise BudgetError(f"{service}: service template unavailable")
    template_row = revision_connections(
        {
            "metadata": {
                "name": f"{service}-candidate-template",
                "annotations": (template.get("metadata") or {}).get("annotations"),
            },
            "spec": template.get("spec"),
        },
        service,
        settings,
        database_connection_name,
    )
    traffic = (service_doc.get("status") or {}).get("traffic")
    if not isinstance(traffic, list):
        raise BudgetError(f"{service}: service traffic unavailable")
    serving = [
        target.get("revisionName")
        for target in traffic
        if positive_int(
            target.get("percent", 0), f"{service} traffic percent", zero_ok=True
        ) > 0
    ]
    if len(serving) != 1 or not isinstance(serving[0], str) or sum(
        positive_int(
            target.get("percent", 0), f"{service} traffic percent", zero_ok=True
        )
        for target in traffic
    ) != 100:
        raise BudgetError(f"{service}: inherited candidate needs one 100% serving revision")
    matching = [
        revision
        for revision in revisions
        if (revision.get("metadata") or {}).get("name") == serving[0]
    ]
    if len(matching) != 1:
        raise BudgetError(f"{service}: serving revision inventory is ambiguous")
    serving_row = revision_connections(
        matching[0], service, settings, database_connection_name
    )
    policy_row = candidate_connections(service, settings)
    largest = max(
        (policy_row, template_row, serving_row),
        key=lambda row: row["connections"],
    )
    return {
        **policy_row,
        "max_instances": largest["max_instances"],
        "workers_per_instance": largest["workers_per_instance"],
        "connections_per_worker": largest["connections_per_worker"],
        "connections": largest["connections"],
    }


def service_budget(
    service: str,
    settings: dict[str, Any],
    service_doc: dict[str, Any],
    revisions: list[dict[str, Any]],
    database_connection_name: str,
) -> list[dict[str, Any]]:
    traffic = (service_doc.get("status") or {}).get("traffic")
    if not isinstance(traffic, list) or not traffic:
        raise BudgetError(f"{service}: service traffic unavailable")
    referenced: set[str] = set()
    for target in traffic:
        revision = target.get("revisionName")
        if not isinstance(revision, str):
            raise BudgetError(f"{service}: traffic target has no revision name")
        percent = target.get("percent", 0)
        if positive_int(
            percent, f"{service} traffic percent", zero_ok=True
        ) > 0 or target.get("tag"):
            referenced.add(revision)
    if not referenced:
        raise BudgetError(f"{service}: no serving or tagged revision")
    status = service_doc.get("status") or {}
    latest = status.get("latestReadyRevisionName")
    if latest:
        referenced.add(latest)  # in-flight or just-created candidate
    by_name = {(rev.get("metadata") or {}).get("name"): rev for rev in revisions}
    missing = referenced - by_name.keys()
    if missing:
        raise BudgetError(
            f"{service}: referenced revisions missing from inventory: {sorted(missing)}"
        )
    # Keep the newest unreferenced revision as the rollback allowance. A tagged
    # rollback is already in referenced and is not counted twice.
    unreferenced = [
        rev
        for rev in revisions
        if (rev.get("metadata") or {}).get("name") not in referenced
    ]
    if unreferenced:
        rollback = max(
            unreferenced,
            key=lambda rev: (rev.get("metadata") or {}).get("creationTimestamp", ""),
        )
        referenced.add(rollback["metadata"]["name"])
    if settings.get("count_retained_revisions"):
        # Deferred UAT retirement allows several old generations to drain at
        # once. Until they are deleted, reserve each one's full connection cap.
        referenced.update(by_name)
    return [
        revision_connections(by_name[name], service, settings, database_connection_name)
        for name in sorted(referenced)
    ]


def job_budget(
    job: dict[str, Any], settings: dict[str, Any], database_connection_name: str
) -> dict[str, Any]:
    name = (job.get("metadata") or {}).get("name")
    spec = ((job.get("spec") or {}).get("template") or {}).get("spec") or {}
    annotations = (
        ((job.get("spec") or {}).get("template") or {})
        .get("metadata", {})
        .get("annotations", {})
    )
    task = (spec.get("template") or {}).get("spec") or {}
    task_count = positive_int(spec.get("taskCount"), f"{name} task count")
    # The API omits parallelism when it uses the default. Task count is the
    # conservative ceiling, regardless of which default Cloud Run applies.
    parallelism = positive_int(
        spec.get("parallelism", task_count), f"{name} parallelism"
    )
    configured = positive_int(
        settings["connections_per_task"], f"{name} connections per task"
    )
    executions = positive_int(
        settings["concurrent_executions"], f"{name} concurrent executions"
    )
    attached = database_connection_name in annotations.get(
        "run.googleapis.com/cloudsql-instances", ""
    ).split(",")
    containers = task.get("containers") or []
    if not isinstance(containers, list) or not containers:
        raise BudgetError(f"{name}: task containers unavailable")
    live_pool = 0
    for container in containers:
        live_pool += pool_capacity(container, name, required=False)
    if not attached and live_pool:
        raise BudgetError(
            f"{name}: DB pools configured without expected Cloud SQL attachment"
        )
    per_task = max(configured, live_pool) if attached else configured
    connections = min(parallelism, task_count) * executions * per_task
    return {
        "name": name,
        "parallel_tasks": min(parallelism, task_count),
        "concurrent_executions": executions,
        "connections_per_task": per_task,
        "cloudsql_attached": attached,
        "connections": connections,
    }


def connection_policy(
    profile: dict[str, Any], environment: str | None = None
) -> dict[str, int]:
    """Resolve one complete policy; incomplete overrides never inherit authority."""
    if profile.get("schema_version") != 1:
        raise BudgetError("unsupported capacity profile version")
    config = profile["environments"][environment] if environment else {}
    fields = ("database_max_connections", "admission_limit", "administrative_reserve")
    source = config.get("connection_policy", profile)
    if not isinstance(source, dict) or any(field not in source for field in fields):
        raise BudgetError("incomplete database connection policy")
    policy = {field: positive_int(source[field], field) for field in fields}
    if (
        policy["admission_limit"] > policy["database_max_connections"]
        or policy["administrative_reserve"] >= policy["admission_limit"]
    ):
        raise BudgetError("invalid database connection policy")
    return policy


def verify_frontend_without_sql(
    workload: dict[str, Any], *, name: str, template: bool, project: str
) -> None:
    """Check the frontend's declared Cloud Run configuration for SQL bindings.

    This is an incremental admission check. It is deliberately restricted to
    the reviewed web runtime identity and never classifies arbitrary jobs as
    database-free.
    """
    metadata = workload.get("metadata") or {}
    if not template and metadata.get("name") != name:
        raise BudgetError(f"{name}: frontend revision identity is ambiguous")
    annotations = metadata.get("annotations") or {}
    if not isinstance(annotations, dict) or any(
        "cloudsql" in str(key).lower() or "cloud-sql" in str(key).lower()
        for key in annotations
    ):
        raise BudgetError(f"{name}: frontend Cloud SQL attachment is present or uninspectable")
    spec = workload.get("spec") or {}
    expected_account = f"hushh-webapp-runtime@{project}.iam.gserviceaccount.com"
    if spec.get("serviceAccountName") != expected_account:
        raise BudgetError(f"{name}: frontend runtime identity differs from reviewed identity")
    containers = spec.get("containers")
    if not isinstance(containers, list) or len(containers) != 1:
        raise BudgetError(f"{name}: frontend container inventory is unavailable")
    if spec.get("volumes"):
        raise BudgetError(f"{name}: frontend volumes require a database access review")
    env = containers[0].get("env")
    if not isinstance(env, list):
        raise BudgetError(f"{name}: frontend environment inventory is unavailable")
    for item in env:
        if not isinstance(item, dict) or not isinstance(item.get("name"), str):
            raise BudgetError(f"{name}: frontend environment inventory is malformed")
        secret_ref = ((item.get("valueFrom") or {}).get("secretKeyRef") or {})
        if (
            FRONTEND_DB_ENV.match(item["name"])
            or FRONTEND_DB_VALUE.search(str(item.get("value", "")))
            or FRONTEND_DB_ENV.match(str(secret_ref.get("name", "")))
        ):
            raise BudgetError(f"{name}: frontend database configuration is present")


def verify_frontend_project_iam(project: str) -> None:
    """Reject direct project grants beyond the web runtime's reviewed roles."""
    policy = gcloud_json("projects", "get-iam-policy", project)
    bindings = policy.get("bindings")
    if not isinstance(bindings, list):
        raise BudgetError("frontend project IAM inventory is unavailable")
    member = f"serviceAccount:hushh-webapp-runtime@{project}.iam.gserviceaccount.com"
    for binding in bindings:
        if not isinstance(binding, dict) or not isinstance(binding.get("members"), list):
            raise BudgetError("frontend project IAM inventory is malformed")
        if member in binding["members"] and binding.get("role") not in FRONTEND_ALLOWED_PROJECT_ROLES:
            raise BudgetError("frontend runtime identity has an unreviewed project IAM role")


def frontend_only_report(
    profile: dict[str, Any], environment: str, *, candidate_revision: str | None = None
) -> dict[str, Any]:
    """Admit a reviewed web-only release by its zero declared SQL demand.

    A web release does not create a database service revision. Global SQL
    inventory, including unrelated temporary jobs, is therefore not an
    admission dependency for this narrow lane. Backend/all releases retain the
    full fail-closed capacity calculation.
    """
    if environment != "uat":
        raise BudgetError("frontend-only incremental admission is limited to UAT")
    policy = connection_policy(profile, environment)
    config = profile["environments"][environment]
    if FRONTEND_SERVICE not in config.get("non_database_services", ()):
        raise BudgetError("frontend service lacks reviewed non-database classification")
    project, region = config["project"], profile["region"]
    verify_frontend_project_iam(project)
    opts = (f"--project={project}", f"--region={region}")
    service = gcloud_json("run", "services", "describe", FRONTEND_SERVICE, *opts)
    template = (service.get("spec") or {}).get("template")
    if not isinstance(template, dict):
        raise BudgetError("frontend service template is unavailable")
    verify_frontend_without_sql(
        template, name=f"{FRONTEND_SERVICE} template", template=True, project=project
    )
    status = service.get("status") or {}
    traffic = status.get("traffic")
    if not isinstance(traffic, list) or not traffic:
        raise BudgetError("frontend serving traffic is unavailable")
    revision_names: set[str] = set()
    serving_percent = 0
    for target in traffic:
        revision_name = target.get("revisionName")
        percent = positive_int(
            target.get("percent", 0), "frontend traffic percent", zero_ok=True
        )
        if not isinstance(revision_name, str) or not revision_name.startswith(
            f"{FRONTEND_SERVICE}-"
        ):
            raise BudgetError("frontend traffic revision identity is invalid")
        serving_percent += percent
        if percent or target.get("tag"):
            revision_names.add(revision_name)
    if serving_percent != 100:
        raise BudgetError("frontend serving traffic is not exactly 100%")
    latest = status.get("latestReadyRevisionName")
    if not isinstance(latest, str) or not latest.startswith(f"{FRONTEND_SERVICE}-"):
        raise BudgetError("frontend latest ready revision is unavailable")
    revision_names.add(latest)
    if candidate_revision is not None:
        if not re.fullmatch(r"hushh-webapp-[a-z0-9-]+", candidate_revision):
            raise BudgetError("frontend candidate revision identity is invalid")
        revision_names.add(candidate_revision)
    for revision_name in sorted(revision_names):
        revision = gcloud_json("run", "revisions", "describe", revision_name, *opts)
        verify_frontend_without_sql(
            revision, name=revision_name, template=False, project=project
        )
    return {
        "environment": environment,
        "phase": "pre-deploy",
        "project": project,
        "admission_mode": "frontend-only-incremental",
        "projected_connections": 0,
        "incremental_connections": 0,
        "admission_limit": policy["admission_limit"],
        "admitted": True,
        "verified_frontend_revisions": sorted(revision_names),
    }


def sql_alert_thresholds(
    profile: dict[str, Any], project: str, instance: str
) -> dict[str, int]:
    matches = [name for name, config in profile["environments"].items()
               if config["project"] == project]
    if len(matches) != 1:
        raise BudgetError("expected one reviewed capacity policy for the project")
    environment = matches[0]
    if profile["environments"][environment]["database_instance"] != instance:
        raise BudgetError("SQL instance differs from reviewed capacity policy")
    maximum = connection_policy(profile, environment)["database_max_connections"]
    return {"warning": maximum * 70 // 100, "critical": maximum * 85 // 100}


def evaluate(
    profile: dict[str, Any],
    environment: str,
    inventory: dict[str, Any],
    *,
    phase: CapacityPhase = "pre-deploy",
    candidate_services: frozenset[str] | None = None,
    inherited_candidate_services: frozenset[str] = frozenset(),
    maintenance_profile: str | None = None,
) -> dict[str, Any]:
    if phase not in CAPACITY_PHASES:
        raise BudgetError(f"unsupported capacity phase: {phase}")
    policy = connection_policy(profile, environment)
    config = profile["environments"][environment]
    maintenance = None
    if maintenance_profile is not None:
        bootstrap_recovery = maintenance_profile == "serving_backend_clone_v2"
        expected = {"service": "consent-protocol", "candidate": {
            "max_instances": 1, "workers_per_instance": 1 if bootstrap_recovery else 2, "asyncpg_pool_max": 4 if bootstrap_recovery else 2,
            "sqlalchemy_pool_size": 2, "sqlalchemy_max_overflow": 0}}
        if (environment != "production" or phase != "pre-deploy"
                or maintenance_profile not in {"serving_backend_clone_v1", "serving_backend_clone_v2"}
                or inherited_candidate_services
                or config.get("maintenance_candidates", {}).get(maintenance_profile) != expected):
            raise BudgetError("unreviewed maintenance capacity profile")
        maintenance = expected
        # Reserve all ordinary worker candidates and jobs too. This is not a
        # caller-controlled reduction of the global budget or ordinary release.
        if candidate_services is not None:
            raise BudgetError("maintenance profile cannot narrow candidate services")
        if bootstrap_recovery:
            # This operation creates only its backend clone. Retained workers
            # and all jobs still count; ordinary releases reserve new workers.
            candidate_services = frozenset({"consent-protocol"})
    if candidate_services is None:
        candidate_services = frozenset(config["services"])
    if candidate_services - config["services"].keys():
        raise BudgetError("candidate service is not in the capacity profile")
    if inherited_candidate_services - candidate_services:
        raise BudgetError("inherited candidate must be a reserved candidate service")
    maximum = policy["database_max_connections"]
    limit = policy["admission_limit"]
    reserve = policy["administrative_reserve"]
    live_maximum = inventory["database_max_connections"]
    if live_maximum != maximum:
        raise BudgetError(
            f"Cloud SQL max_connections is {live_maximum}; profile requires {maximum}"
        )
    connection_name = (
        f"{config['project']}:{profile['region']}:{config['database_instance']}"
    )
    service_rows: list[dict[str, Any]] = []
    expected_services = set(config["services"])
    optional_services = {
        name
        for name, settings in config["services"].items()
        if settings.get("optional_existing")
    }
    if (
        not expected_services - optional_services <= set(inventory["services"])
        or set(inventory["services"]) - expected_services
    ):
        raise BudgetError("service inventory differs from capacity profile")
    for name, settings in config["services"].items():
        if name in inventory["services"]:
            service = inventory["services"][name]
            service_rows.extend(
                service_budget(
                    name,
                    settings,
                    service["service"],
                    service["revisions"],
                    connection_name,
                )
            )
        if phase == "pre-deploy" and name in candidate_services:
            if name in inherited_candidate_services:
                if name not in inventory["services"]:
                    raise BudgetError(f"{name}: inherited candidate has no live service")
                service = inventory["services"][name]
                service_rows.append(
                    inherited_candidate_connections(
                        name,
                        settings,
                        service["service"],
                        service["revisions"],
                        connection_name,
                    )
                )
            else:
                effective = {**settings, "candidate": maintenance["candidate"]} if maintenance and name == maintenance["service"] else settings
                service_rows.append(candidate_connections(name, effective))
    if set(inventory["jobs"]) != set(config["jobs"]):
        extra = set(inventory["jobs"]) - set(config["jobs"])
        missing = set(config["jobs"]) - set(inventory["jobs"])
        raise BudgetError(
            f"job inventory drift: unprofiled={sorted(extra)}, missing={sorted(missing)}"
        )
    job_rows = [
        job_budget(inventory["jobs"][name], settings, connection_name)
        for name, settings in config["jobs"].items()
    ]
    projected = reserve + sum(row["connections"] for row in service_rows + job_rows)
    return {
        "environment": environment,
        "phase": phase,
        "project": config["project"],
        "database": connection_name,
        "verified_max_connections": live_maximum,
        "admission_limit": limit,
        "administrative_reserve": reserve,
        "services": service_rows,
        "jobs": job_rows,
        "projected_connections": projected,
        "headroom_to_limit": limit - projected,
        "admitted": projected <= limit,
    }


def collect(profile: dict[str, Any], environment: str) -> dict[str, Any]:
    config = profile["environments"][environment]
    project, region = config["project"], profile["region"]
    sql = gcloud_json(
        "sql",
        "instances",
        "describe",
        config["database_instance"],
        f"--project={project}",
    )
    if sql.get("state") != "RUNNABLE":
        raise BudgetError(f"Cloud SQL instance is not RUNNABLE: {sql.get('state')}")
    flags = (sql.get("settings") or {}).get("databaseFlags") or []
    if not any(
        flag.get("name") == "cloudsql.iam_authentication" and flag.get("value") == "on"
        for flag in flags
    ):
        raise BudgetError("Cloud SQL IAM authentication flag is not on")
    values = [
        flag.get("value") for flag in flags if flag.get("name") == "max_connections"
    ]
    if len(values) != 1:
        raise BudgetError(
            "Cloud SQL max_connections must be explicitly configured and readable"
        )
    maximum = positive_int(values[0], "Cloud SQL max_connections")
    opts = (f"--project={project}", f"--region={region}")
    listed_services = gcloud_json("run", "services", "list", *opts)
    if not isinstance(listed_services, list):
        raise BudgetError("Cloud Run services inventory unavailable")
    service_names = {
        (service.get("metadata") or {}).get("name") for service in listed_services
    }
    profiled = set(config["services"])
    non_database = set(config["non_database_services"])
    if None in service_names:
        raise BudgetError("Cloud Run service inventory contains an unnamed service")
    if service_names - profiled != non_database:
        raise BudgetError(
            f"Cloud Run service inventory drift: unprofiled={sorted((service_names - profiled) - non_database)}, "
            f"missing declared non-DB={sorted(non_database - service_names)}"
        )
    required = {
        name
        for name, settings in config["services"].items()
        if not settings.get("optional_existing")
    }
    if required - service_names:
        raise BudgetError(
            f"required database services missing: {sorted(required - service_names)}"
        )
    services: dict[str, Any] = {}
    for name in service_names:
        opts = (f"--project={project}", f"--region={region}")
        service = gcloud_json("run", "services", "describe", name, *opts)
        revisions = gcloud_json("run", "revisions", "list", f"--service={name}", *opts)
        if not isinstance(revisions, list):
            raise BudgetError(f"{name}: revision inventory unavailable")
        if name in non_database:
            connection_name = f"{project}:{region}:{config['database_instance']}"
            traffic = (service.get("status") or {}).get("traffic")
            if not isinstance(traffic, list):
                raise BudgetError(f"{name}: traffic unavailable")
            referenced = {
                target.get("revisionName")
                for target in traffic
                if target.get("tag") or target.get("percent", 0)
            }
            latest = (service.get("status") or {}).get("latestReadyRevisionName")
            if latest:
                referenced.add(latest)
            by_name = {
                (rev.get("metadata") or {}).get("name"): rev for rev in revisions
            }
            if None in referenced or referenced - by_name.keys():
                raise BudgetError(f"{name}: referenced revision unavailable")
            for revision in (by_name[revision_name] for revision_name in referenced):
                annotations = (revision.get("metadata") or {}).get("annotations") or {}
                if connection_name in annotations.get(
                    "run.googleapis.com/cloudsql-instances", ""
                ).split(","):
                    raise BudgetError(
                        f"{name}: reachable revision attaches to budgeted Cloud SQL"
                    )
        else:
            services[name] = {"service": service, "revisions": revisions}
    listed = gcloud_json("run", "jobs", "list", *opts)
    if not isinstance(listed, list):
        raise BudgetError("Cloud Run jobs inventory unavailable")
    names = [(job.get("metadata") or {}).get("name") for job in listed]
    if any(not isinstance(name, str) for name in names) or len(names) != len(
        set(names)
    ):
        raise BudgetError("Cloud Run jobs inventory malformed")
    jobs = {name: gcloud_json("run", "jobs", "describe", name, *opts) for name in names}
    return {"database_max_connections": maximum, "services": services, "jobs": jobs}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--environment", choices=("uat", "production"), required=True)
    parser.add_argument(
        "--phase",
        choices=CAPACITY_PHASES,
        default="pre-deploy",
        help="Reserve the next deployment candidate, or check only retained capacity",
    )
    parser.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    candidates = parser.add_mutually_exclusive_group()
    candidates.add_argument(
        "--candidate-service",
        action="append",
        help="Reserve a new revision of this service (repeat for each deployed service)",
    )
    candidates.add_argument(
        "--inherit-candidate-service",
        action="append",
        help="Reserve a candidate inheriting this live service's template (repeatable)",
    )
    candidates.add_argument(
        "--no-candidates",
        action="store_true",
        help="Audit the global database budget without reserving a new service revision",
    )
    candidates.add_argument(
        "--frontend-only",
        action="store_true",
        help="Verify UAT web service has zero incremental SQL demand without auditing unrelated jobs",
    )
    parser.add_argument(
        "--frontend-revision",
        help="Also verify this exact frontend candidate revision before traffic promotion",
    )
    parser.add_argument(
        "--report-only",
        action="store_true",
        help="Report an over-budget result without a nonzero exit",
    )
    parser.add_argument("--output", choices=("text", "json"), default="text")
    args = parser.parse_args()
    try:
        profile = json.loads(args.profile.read_text())
        if args.frontend_only:
            if args.phase != "pre-deploy":
                raise BudgetError("frontend-only admission requires the pre-deploy phase")
            report = frontend_only_report(
                profile, args.environment, candidate_revision=args.frontend_revision
            )
        else:
            if args.frontend_revision:
                raise BudgetError("frontend revision verification requires --frontend-only")
            candidate_services = (
                frozenset()
                if args.no_candidates
                else frozenset(args.candidate_service)
                if args.candidate_service is not None
                else frozenset(args.inherit_candidate_service)
                if args.inherit_candidate_service is not None
                else None
            )
            report = evaluate(
                profile,
                args.environment,
                collect(profile, args.environment),
                phase=args.phase,
                candidate_services=candidate_services,
                inherited_candidate_services=frozenset(args.inherit_candidate_service or ()),
            )
    except (OSError, KeyError, TypeError, json.JSONDecodeError, BudgetError) as exc:
        print(f"capacity budget blocked: {exc}", file=sys.stderr)
        return 2
    if args.output == "json":
        print(json.dumps(report, indent=2, sort_keys=True))
    elif args.frontend_only:
        print(
            f"{args.environment}: frontend-only incremental Cloud SQL demand 0 "
            "(service template and reachable revisions verified without SQL bindings)"
        )
        print("ADMIT")
    else:
        capacity_label = "projected" if args.phase == "pre-deploy" else "current"
        print(
            f"{args.environment}: {capacity_label} {report['projected_connections']} / {report['admission_limit']} "
            f"(Cloud SQL max {report['verified_max_connections']}, admin reserve {report['administrative_reserve']})"
        )
        for row in report["services"] + report["jobs"]:
            print(f"  {row['name']}: {row['connections']}")
        print("ADMIT" if report["admitted"] else "BLOCK: connection budget exceeded")
    return 0 if report["admitted"] or args.report_only else 1


if __name__ == "__main__":
    raise SystemExit(main())

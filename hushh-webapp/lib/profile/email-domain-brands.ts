export function resolveEmailDomainBrand(email: string | null | undefined) {
  const normalized = email?.trim().toLowerCase();
  if (!normalized || !/^[^@\s]+@[^@\s]+$/.test(normalized)) return undefined;
  const domain = normalized.slice(normalized.indexOf("@") + 1);
  return EMAIL_DOMAIN_BRANDS.find((brand) => brand.domains.some((candidate) => candidate === domain));
}

import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "../..");
const sourcePath = path.join(
  webRoot,
  "contracts/kai/one-capability-graph.v1.json",
);
const outputPath = path.join(
  webRoot,
  "lib/generated/one-location-workflow-card-catalog.v1.ts",
);
const check = process.argv.includes("--check");

const graph = JSON.parse(readFileSync(sourcePath, "utf8"));
const workflow = (graph.workflows ?? []).find(
  (candidate) => candidate?.capability_id === "workflow.setup.location",
);
if (!workflow || !Array.isArray(workflow.interaction_surfaces)) {
  throw new Error("CapabilityGraphV1 has no Location interaction projection.");
}
const revisionCompatibility = graph.workflow_revision_compatibility;
const workflowRevisionPolicy = revisionCompatibility?.workflows?.find(
  (candidate) => candidate?.workflow_id === "workflow.setup.location",
);
if (
  revisionCompatibility?.schema_version !==
    "one.workflow_revision_compatibility.v1" ||
  revisionCompatibility.current_graph_revision !== graph.revision ||
  !workflowRevisionPolicy ||
  workflowRevisionPolicy.workflow_version !== workflow.version ||
  !Array.isArray(workflowRevisionPolicy.compatible_graph_revisions)
) {
  throw new Error("CapabilityGraphV1 has no valid Location revision policy.");
}
const telemetryPolicy = workflow.telemetry_policy;
if (
  telemetryPolicy?.schema_version !== "one.location_telemetry_policy.v1" ||
  telemetryPolicy.event_schema !== "one.voice_telemetry.v2" ||
  !Array.isArray(telemetryPolicy.event_ids) ||
  telemetryPolicy.event_ids.length === 0 ||
  telemetryPolicy.event_ids.some(
    (eventId) =>
      typeof eventId !== "string" ||
      !/^one\.location\.[a-z0-9_]+$/u.test(eventId),
  ) ||
  new Set(telemetryPolicy.event_ids).size !== telemetryPolicy.event_ids.length
) {
  throw new Error("CapabilityGraphV1 has no valid Location telemetry policy.");
}

const variants = workflow.interaction_surfaces.map((surface) => {
  if (
    surface?.status !== "wired" ||
    surface.render_surface !== "render.one_location_workflow_card" ||
    surface.render_capability_id !== "render.one_location_workflow_card" ||
    surface.surface_id !== surface.variant_id ||
    typeof surface.directive_kind !== "string" ||
    typeof surface.title_key !== "string" ||
    typeof surface.body_key !== "string" ||
    !Array.isArray(surface.allowed_results) ||
    surface.allowed_results.length === 0 ||
    !surface.result_schema
  ) {
    throw new Error("Location interaction projection is incomplete or unbound.");
  }
  return {
    contractId: surface.variant_id,
    kind: surface.directive_kind,
    titleKey: surface.title_key,
    bodyKey: surface.body_key,
    results: surface.allowed_results.map((result) => {
      if (
        typeof result?.result !== "string" ||
        typeof result?.label_key !== "string" ||
        typeof result?.presentation !== "string" ||
        (result.button_role !== null &&
          result.button_role !== "primary" &&
          result.button_role !== "secondary")
      ) {
        throw new Error("Location interaction result projection is invalid.");
      }
      return {
        result: result.result,
        labelKey: result.label_key,
        presentation: result.presentation,
        buttonRole: result.button_role,
      };
    }),
    resultSchema: surface.result_schema,
  };
});

const seen = new Set();
for (const variant of variants) {
  if (seen.has(variant.contractId)) {
    throw new Error(`Duplicate Location interaction: ${variant.contractId}`);
  }
  seen.add(variant.contractId);
}

const projection = {
  schemaVersion: "one.location_workflow_card_catalog.v1",
  graphRevision: graph.revision,
  compatibleGraphRevisions: [
    ...workflowRevisionPolicy.compatible_graph_revisions,
  ].sort(),
  workflowId: workflow.capability_id,
  workflowVersion: workflow.version,
  renderSurface: "render.one_location_workflow_card",
  telemetrySchemaVersion: telemetryPolicy.event_schema,
  telemetryEventIds: [...telemetryPolicy.event_ids].sort(),
  variants: variants.sort((left, right) =>
    left.contractId.localeCompare(right.contractId),
  ),
};
const encoded = `// Generated by scripts/voice/generate-one-location-workflow-card-catalog.mjs.\n// Do not edit by hand; update CapabilityGraphV1 and regenerate.\nexport const ONE_LOCATION_WORKFLOW_CARD_CATALOG = ${JSON.stringify(projection, null, 2)} as const;\n`;

if (check) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== encoded) {
    throw new Error(
      "Location workflow card catalog is stale. Run npm run build:capability-graph.",
    );
  }
} else {
  writeFileSync(outputPath, encoded);
}

import React, { StrictMode } from "react";
import { render, screen, fireEvent, act, cleanup } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { WalletLiveCardCapture } from "@/components/wallet/wallet-live-card-capture";
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("stops a late StrictMode stream and the current stream on cancel", async () => {
  const resolve: ((value: MediaStream) => void)[] = [];
  const getUserMedia = vi.fn(() => new Promise<MediaStream>(done => resolve.push(done)));
  vi.stubGlobal("navigator", { mediaDevices: { getUserMedia } });
  const staleStop = vi.fn(), currentStop = vi.fn(), onCancel = vi.fn();
  render(<StrictMode><WalletLiveCardCapture onPhoto={vi.fn()} onCancel={onCancel} /></StrictMode>);
  expect(getUserMedia).toHaveBeenCalledTimes(2);
  await act(async () => resolve[1]!({ getTracks: () => [{ stop: currentStop }] } as unknown as MediaStream));
  await act(async () => resolve[0]!({ getTracks: () => [{ stop: staleStop }] } as unknown as MediaStream));
  expect(staleStop).toHaveBeenCalledOnce(); expect(currentStop).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "Cancel", exact: true }));
  expect(currentStop).toHaveBeenCalledOnce(); expect(onCancel).toHaveBeenCalledOnce();
  cleanup(); expect(currentStop).toHaveBeenCalledOnce();
});
it("waits for a frame and offers a photo fallback after capture failure", async () => {
  const stop = vi.fn(), choose = vi.fn(), onPhoto = vi.fn();
  vi.stubGlobal("navigator", { mediaDevices: { getUserMedia: vi.fn().mockResolvedValue({ getTracks: () => [{ stop }] }) } });
  const { container } = render(<WalletLiveCardCapture onPhoto={onPhoto} onCancel={vi.fn()} onChoosePhoto={choose} />);
  await act(async () => {});
  const video = container.querySelector("video")!;
  Object.defineProperties(video, { videoWidth: { value: 1920 }, videoHeight: { value: 1080 }, readyState: { value: 2 } });
  vi.spyOn(video, "getBoundingClientRect").mockReturnValue({ width: 400, height: 250 } as DOMRect);
  fireEvent.loadedMetadata(video);
  const capture = screen.getByRole("button", { name: "Take photo", exact: true });
  expect(capture).toBeDisabled();
  fireEvent.loadedData(video); expect(capture).toBeEnabled();
  vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockImplementation(() => { throw new Error("Synthetic capture failure"); });
  fireEvent.click(capture);
  expect(screen.getByRole("status")).toHaveTextContent("Camera unavailable");
  fireEvent.click(screen.getByRole("button", { name: "Choose from photos", exact: true }));
  expect(stop).toHaveBeenCalledOnce(); expect(choose).toHaveBeenCalledOnce(); expect(onPhoto).not.toHaveBeenCalled();
});
